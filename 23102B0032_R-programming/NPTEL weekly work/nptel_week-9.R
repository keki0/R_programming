# ------------------------------------------------------------
# 6. Convert dates into pieces
# ------------------------------------------------------------

dates = c(
  "2020-07-24",
  "2021-08-25",
  "2022-09-26",
  "2023-10-27"
)

dates


# Split the dates

datesplt = strsplit(
  dates,
  "-"
)

datesplt


# ------------------------------------------------------------
# 7. Convert split dates into a character matrix
# ------------------------------------------------------------

datemat = matrix(
  unlist(datesplt),
  nrow = 4,
  ncol = 3,
  byrow = TRUE
)

datemat


# ------------------------------------------------------------
# 8. Convert split dates into a numeric matrix
# ------------------------------------------------------------

datematrix = matrix(
  as.numeric(unlist(datesplt)),
  nrow = 4,
  ncol = 3,
  byrow = TRUE
)

datematrix


