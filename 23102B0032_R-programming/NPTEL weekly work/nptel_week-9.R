# ------------------------------------------------------------
# 1. print() - Printing multiple items
# ------------------------------------------------------------

# print() can print one object at a time

print("The zero occurs at")
print(2*pi)
print("radians")


# ------------------------------------------------------------
# 2. cat() - Combining multiple items
# ------------------------------------------------------------

cat("The zero occurs at", 2*pi, "radians.", "\n")


# ------------------------------------------------------------
# 3. Display today's date using cat()
# ------------------------------------------------------------

d = date()

cat("Today's date is:", d, "\n")


# ------------------------------------------------------------
# 4. cat() with separator
# ------------------------------------------------------------

x = 1:10

x

cat(x, sep = " ++ ")

cat("\n")

cat(x, sep = " / ")

cat("\n")


# ------------------------------------------------------------
# 5. cat() with calculations
# ------------------------------------------------------------

x = 7

cat("The square of", x, "is", x^2, "!\n")


# ------------------------------------------------------------
# 6. cat() with format()
# ------------------------------------------------------------

cat(
  "The square root of",
  x,
  "is approximately",
  format(sqrt(x), digits = 3),
  "\n"
)


# ------------------------------------------------------------
# 7. cat() with a vector
# ------------------------------------------------------------

evenno = c(2, 4, 6, 8, 10)

evenno

cat(
  "The first few even numbers are:",
  evenno,
  "...\n"
)


# ------------------------------------------------------------
# 8. cat() with fill and labels
# ------------------------------------------------------------

x = 1:10

x

cat(
  x,
  fill = 2,
  labels = paste("(", letters[1:10], "):")
)


