# ------------------------------------------------------------
# 3. Creating Factor using factor()
# ------------------------------------------------------------

y = c(1, 4, 3, 5, 4, 2, 4)

possible.dieface = c(1, 2, 3, 4, 5, 6)

labels.dieface = c(
  "one",
  "two",
  "three",
  "four",
  "five",
  "six"
)

facy = factor(
  y,
  levels = possible.dieface,
  labels = labels.dieface
)

facy


